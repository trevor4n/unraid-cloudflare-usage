#!/bin/bash
# Assemble cloudflare.usage.plg from src/. Every file is inlined, so installing the
# plugin downloads nothing.
#
#   ./build.sh [version]    version defaults to today's date, YYYY.MM.DD
#
# Set PLUGIN_URL to where the .plg will be published (a public https URL) to
# add pluginURL, which lets Unraid check for updates and lets UnraidClaw's
# unraid_plugin_install fetch it.
set -euo pipefail
cd "$(dirname "$0")"

VERSION=${1:-$(date +%Y.%m.%d)}
PLUG=/usr/local/emhttp/plugins/cloudflare.usage
OUT=${PLG_OUT:-cloudflare.usage.plg}   # the tests build elsewhere so they never touch the release file
URL_ATTR=""
if [[ -n ${PLUGIN_URL:-} ]]; then
  [[ $PLUGIN_URL =~ ^https://[A-Za-z0-9./_-]+\.plg$ ]] || { echo "build: PLUGIN_URL must be an https URL ending in .plg" >&2; exit 1; }
  URL_ATTR=" pluginURL=\"$PLUGIN_URL\""
fi

# name in plugin dir | source | mode
FILES=(
  "README.md|src/plugin-README.md|0644"
  "CloudflareUsageTile.page|src/CloudflareUsageTile.page|0644"
  "CloudflareUsage.page|src/CloudflareUsage.page|0644"
  "include/tile.php|src/include/tile.php|0644"
  "include/settings_lib.php|src/include/settings_lib.php|0644"
  "include/save.php|src/include/save.php|0644"
  "tile.css|src/tile.css|0644"
  "tile.js|src/tile.js|0644"
  "scripts/poll|src/scripts/poll|0755"
  "cloudflare.usage.cron|src/cloudflare.usage.cron|0644"
  "cloudflare.usage.cfg.default|src/cloudflare.usage.cfg.default|0644"
)

# Release notes go into the plugin unescaped, so keep XML specials out of them.
if grep -q '[<&]' CHANGES.md; then echo "build: CHANGES.md must not contain < or &" >&2; exit 1; fi
grep -qx "###$VERSION" CHANGES.md || echo "build: warning: CHANGES.md has no entry for $VERSION" >&2

cdata() { # file -> CDATA block; refuses content that would end it early
  if grep -q ']]>' "$1"; then echo "build: $1 contains ']]>'" >&2; exit 1; fi
  printf '<![CDATA[\n'; sed "s/@VERSION@/$VERSION/g" "$1"; printf ']]>'
}

{
  cat <<EOF
<?xml version='1.0' standalone='yes'?>
<!DOCTYPE PLUGIN [
<!ENTITY name    "cloudflare.usage">
<!ENTITY author  "Trevor Foren">
<!ENTITY version "$VERSION">
<!ENTITY plugdir "$PLUG">
]>
<!-- Generated by build.sh from src/. Edit the sources, not this file. -->
<PLUGIN name="&name;" author="&author;" version="&version;" min="7.0.0" icon="cloud" launch="Settings/CloudflareUsage" support="https://github.com/trevor4n/unraid-cloudflare-usage/issues"$URL_ATTR>

<CHANGES>
$(cat CHANGES.md)
</CHANGES>

<!-- The plugin manager never overwrites an existing file, so clear the old copy first. -->
<FILE Run="/bin/bash">
<INLINE>
rm -rf &plugdir;
</INLINE>
</FILE>

EOF
  for f in "${FILES[@]}"; do
    IFS='|' read -r name src mode <<<"$f"
    printf '<FILE Name="&plugdir;/%s" Mode="%s">\n<INLINE>' "$name" "$mode"
    cdata "$src"
    printf '</INLINE>\n</FILE>\n\n'
  done
  printf '<FILE Run="/bin/bash">\n<INLINE>'
  cdata src/install.sh
  printf '</INLINE>\n</FILE>\n\n'
  printf '<FILE Run="/bin/bash" Method="remove">\n<INLINE>'
  cdata src/remove.sh
  printf '</INLINE>\n</FILE>\n\n</PLUGIN>\n'
} >"$OUT.tmp"

mv "$OUT.tmp" "$OUT"
echo "built $OUT (version $VERSION, sha256 $(sha256sum "$OUT" | cut -c1-16)...)"
